#!/usr/bin/env python3
"""Turn assets/logo.svg (absolute M/L/H/V/C/Z paths only) into src/LogoPath.h for Drawbot.
Usage: python3 tools/svg_to_drawbot.py assets/logo.svg src/LogoPath.h"""
import re, sys

svg = open(sys.argv[1]).read()
w, h = (float(v) for v in re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg).groups())
ops = []  # (op, args...)
for d in re.findall(r'\sd="([^"]+)"', svg):
    toks = re.findall(r'[MLHVCZ]|-?[\d.]+(?:e-?\d+)?', d)
    i, cmd, x, y = 0, None, 0.0, 0.0
    while i < len(toks):
        if toks[i] in 'MLHVCZ':
            cmd = toks[i]; i += 1
            if cmd == 'Z': ops.append(('Z',)); continue
        n = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6}[cmd]
        a = [float(t) for t in toks[i:i + n]]; i += n
        if cmd == 'H': x = a[0]; ops.append(('L', x, y))
        elif cmd == 'V': y = a[0]; ops.append(('L', x, y))
        else:
            x, y = a[-2], a[-1]; ops.append((cmd,) + tuple(a))
            if cmd == 'M': cmd = 'L'  # implicit lineto after moveto
assert all(o[0] in 'MLCZ' for o in ops), 'unsupported SVG path command'

with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/svg_to_drawbot.py from assets/logo.svg. Do not edit.\n#pragma once\n\n')
    f.write('struct LogoOp { char op; float p[6]; };  // M/L: p[0..1], C: p[0..5], Z: none\n')
    f.write(f'static const float kLogoW = {w!r}f, kLogoH = {h!r}f;\n')
    f.write('static const LogoOp kLogo[] = {\n')
    for o in ops:
        f.write("    {'%s', {%s}},\n" % (o[0], ', '.join(repr(v) + 'f' for v in o[1:])))
    f.write('};\n')
print(f'{len(ops)} ops -> {sys.argv[2]}')
